/**
 * Generates deterministic, realistic `BookedDateRange[]` anchored around the current date
 * so the availability calendar always displays realistic booked ranges & available dates
 * in the current month and upcoming 3 months.
 */
function buildArtistBookedRanges(seedIndex: number): BookedDateRange[] {
  const now = new Date();
  const baseYear = now.getFullYear();
  const baseMonth = now.getMonth();

  const addDaysFromMonthStart = (monthOffset: number, dayNumber: number): string => {
    const d = new Date(baseYear, baseMonth + monthOffset, dayNumber);
    return toDateKey(d);
  };

  const d1 = ((seedIndex * 3) % 18) + 4; // Day 4..21 of current month
  const d2 = ((seedIndex * 5 + 7) % 16) + 10; // Day 10..25 of current month
  const n1 = ((seedIndex * 4 + 3) % 18) + 3; // Next month range 1
  const n2 = ((seedIndex * 6 + 11) % 15) + 12; // Next month range 2
  const m1 = ((seedIndex * 3 + 5) % 20) + 5; // +2 months range

  const ranges: BookedDateRange[] = [
    {
      start: addDaysFromMonthStart(0, d1),
      end: addDaysFromMonthStart(0, d1 + (seedIndex % 2)),
      label: EVENT_LABELS[seedIndex % EVENT_LABELS.length],
    },
    {
      start: addDaysFromMonthStart(0, Math.max(d1 + 3, d2)),
      end: addDaysFromMonthStart(0, Math.max(d1 + 3, d2) + 1),
      label: EVENT_LABELS[(seedIndex + 2) % EVENT_LABELS.length],
    },
    {
      start: addDaysFromMonthStart(1, n1),
      end: addDaysFromMonthStart(1, n1 + (seedIndex % 3 === 0 ? 2 : 1)),
      label: EVENT_LABELS[(seedIndex + 4) % EVENT_LABELS.length],
    },
    {
      start: addDaysFromMonthStart(1, Math.max(n1 + 4, n2)),
      end: addDaysFromMonthStart(1, Math.max(n1 + 4, n2)),
      label: EVENT_LABELS[(seedIndex + 5) % EVENT_LABELS.length],
    },
    {
      start: addDaysFromMonthStart(2, m1),
      end: addDaysFromMonthStart(2, m1 + 1),
      label: EVENT_LABELS[(seedIndex + 1) % EVENT_LABELS.length],
    },
  ];

  return ranges;
}

